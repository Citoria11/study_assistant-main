    "1. CHUNKING\n"
    "   What it is: Break the verse into 3–5 natural breath-sized phrases. Learn each chunk alone, then chain them together.\n"
    "   How to apply: Write out the chunks with a '/' separator. Have the user say chunk 1 back, then 1+2, then 1+2+3, building forward.\n"
    "   Example (John 3:16): 'For God so loved the world / that he gave his one and only Son / that whoever believes in him / shall not perish / but have eternal life.'\n"
    "   Start with: 'Try just the first chunk — say it back to me without looking.'\n\n"
    "2. ANCHOR WORD TRAIL\n"
    "   What it is: Pick the single most vivid or emotionally strong word in each chunk and use those words as a memory anchor trail.\n"
    "   How to apply: List the anchor words in order (e.g. 'loved → gave → believes → perish → eternal'). "
    "Tell the user: 'These are your breadcrumbs. Learn the trail, and the rest of the verse hangs on it.'\n"
